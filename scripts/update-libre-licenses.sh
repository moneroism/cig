# update-libre-licenses.sh <version> - writes libre/licenses-fsf: the SPDX ids the SPDX
# license list marks isFsfLibre (on the FSF's list of free licenses), from the license list's
# tagged release <version> (e.g. 3.29.0). Host only (python3). The libre-meter counts these,
# and the hand-reviewed libre/licenses-cig, as free.
set -euo pipefail
[ $# -eq 1 ] || { echo "usage: $0 <spdx license list version, e.g. 3.29.0>" >&2; exit 1; }
v=$1
REPO=$(cd "$(dirname "$0")/.." && pwd)
t=$(mktemp -d); trap 'rm -rf "$t"' EXIT
curl -fsSL --proto '=https' -o "$t/licenses.json" \
    "https://raw.githubusercontent.com/spdx/license-list-data/v$v/json/licenses.json"
python3 -I - "$t/licenses.json" "$v" > "$t/out" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
if d.get("licenseListVersion") != sys.argv[2]:
    sys.exit("unexpected licenseListVersion %r" % d.get("licenseListVersion"))
print("# SPDX-License-Identifier: GPL-3.0-or-later")
print("# Copyright (C) 2026 moneroism")
print("#")
print("# Generated by scripts/update-libre-licenses.sh from the SPDX license list %s (%s):" % (sys.argv[2], d.get("releaseDate", "?")[:10]))
print("# the licenses it marks isFsfLibre (on the FSF's list of free licenses). Do not edit;")
print("# reviewed additions go to libre/licenses-cig.")
for i in sorted(l["licenseId"] for l in d["licenses"] if l.get("isFsfLibre")):
    print(i)
PY
mv "$t/out" "$REPO/libre/licenses-fsf"
echo "libre/licenses-fsf: $(grep -vc '^#' "$REPO/libre/licenses-fsf") licenses (SPDX $v)"
